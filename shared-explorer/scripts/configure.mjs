import { readFile, mkdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { loadProject, FIELD_NAMES } from './lib/project-config.mjs';

const root = fileURLToPath(new URL('../', import.meta.url));
const check = process.argv.includes('--check');
if (process.argv.slice(2).some(argument => argument !== '--check')) throw new Error('Usage: node scripts/configure.mjs [--check]');
const { project, models, warnings } = await loadProject(root);
const target = path.join(root, 'src/generated');
const literalURL = file => `new URL(${JSON.stringify(path.relative(target, file).split(path.sep).map(encodeURIComponent).join('/'))}, import.meta.url)`;
const header = '// Generated by scripts/configure.mjs. Edit project.config.json and model manifests instead.\n';
let catalog = header + 'const freeze = value => { if (value && typeof value === "object" && !(value instanceof URL)) { Object.values(value).forEach(freeze); Object.freeze(value); } return value; };\nexport const MODEL_CATALOG = freeze({\n';
for (const model of models) {
  const content = JSON.stringify(model.runtime, null, 2).slice(1, -1);
  const urls = Object.entries(model.assets).map(([key, file]) => `${JSON.stringify(FIELD_NAMES[key])}: ${literalURL(file)}`);
  catalog += `${JSON.stringify(model.manifest.id)}: {${content},\n${urls.join(',\n')}\n},\n`;
}
catalog += '});\n';
const config = structuredClone(project), logoFile = config.brand.logoFile; delete config.brand.logoFile;
let projectSource = header + `const project = ${JSON.stringify(config, null, 2)};\n`;
if (logoFile) projectSource += `project.brand.logoUrl = ${literalURL(logoFile)}.href;\n`;
else if (config.brand.logo) projectSource += 'project.brand.logoUrl = project.brand.logo;\n';
projectSource += 'const freeze = value => { if (value && typeof value === "object") { Object.values(value).forEach(freeze); Object.freeze(value); } return value; };\nexport const PROJECT_CONFIG = freeze(project);\n';
await mkdir(target, { recursive: true });
for (const [name, source] of [['catalog.js', catalog], ['project.js', projectSource]]) {
  const file = path.join(target, name); let previous; try { previous = await readFile(file, 'utf8'); } catch {}
  if (previous === source) continue;
  if (check) throw new Error(`${path.relative(root, file)} is stale. Run npm run prepare:project.`);
  await writeFile(file, source);
}
for (const warning of warnings) console.warn(warning);
console.log(`Configured ${project.title}: ${models.length} model package${models.length === 1 ? '' : 's'}.`);
